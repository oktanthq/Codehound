describe("semver range matching", () => {
  it.each(CASES)("$version satisfies $range → $expected", ({ version, range, expected }) => {
    expect(versionSatisfies(version, range)).toBe(expected);
  });

  it("keeps parseSemver compatible with declared package ranges", () => {
    expect(parseSemver("v1.2.3")).toEqual({ major: 1, minor: 2, patch: 3 });
    expect(parseSemver("^4.17.20")).toEqual({ major: 4, minor: 17, patch: 20 });
    expect(parseSemver("~1.2.3-beta")).toEqual({ major: 1, minor: 2, patch: 3 });
    expect(parseSemver("not-a-version")).toBeUndefined();
  });

  it("orders core versions numerically", () => {
    expect(
      compareSemver({ major: 1, minor: 2, patch: 3 }, { major: 1, minor: 2, patch: 4 }),
    ).toBeLessThan(0);
    expect(
      compareSemver({ major: 2, minor: 0, patch: 0 }, { major: 1, minor: 9, patch: 9 }),
    ).toBeGreaterThan(0);
    expect(compareSemver({ major: 1, minor: 0, patch: 0 }, { major: 1, minor: 0, patch: 0 })).toBe(
      0,
    );
  });
});
